"""生成公开版 GitHub Pages 目录：不设口令，打开即是主页；只复制页面实际引用的文件。

源码、口令、图源 PDF、未使用的 WebP 都不会进入 public/。
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

MARKER = '.public-export'   # 只清理本脚本生成过的目录


def referenced_assets(root: Path) -> list[str]:
    page = (root / 'index.html').read_text(encoding='utf-8')
    css = (root / 'assets/style.css').read_text(encoding='utf-8')
    names = set(re.findall(r'assets/[A-Za-z0-9_./-]+', page))
    names |= {'assets/' + n for n in re.findall(r'url\("([A-Za-z0-9_./-]+)"\)', css)}
    for font in [n for n in names if n.startswith('assets/fonts/') and n.endswith('-latin.woff2')]:
        names.add(font.replace('-latin.woff2', '-OFL.txt'))   # 随字体一起分发 OFL 许可证
    missing = sorted(n for n in names if not (root / n).is_file())
    if missing:
        raise SystemExit(f'页面引用了不存在的文件：{missing}')
    return sorted(names)


def with_site_url(page: str, site_url: str) -> str:
    if not site_url:
        return page
    url = site_url.rstrip('/') + '/'
    tags = (f'<link rel="canonical" href="{url}">\n<meta property="og:url" content="{url}">\n'
            f'<meta property="og:image" content="{url}assets/img/mascot-256.png">\n')
    return page.replace('<meta name="theme-color"', tags + '<meta name="theme-color"', 1)


def export_public(root: Path, site_url: str = '') -> Path:
    out = root / 'public'
    if out.exists():
        if not (out / MARKER).exists():
            raise SystemExit(f'{out} 不是本脚本生成的目录，已停止以免覆盖')
        shutil.rmtree(out)
    out.mkdir()
    (out / MARKER).write_text('generated by src/public.py\n', encoding='utf-8')
    page = with_site_url((root / 'index.html').read_text(encoding='utf-8'), site_url)
    (out / 'index.html').write_text(page, encoding='utf-8')
    (out / '.nojekyll').write_text('', encoding='utf-8')
    total = 0
    for name in referenced_assets(root):
        target = out / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(root / name, target)
        total += target.stat().st_size
    print(f'公开版：{out}（{total / 2**20:.1f} MiB 资源），直接打开即为主页，无口令')
    return out
